//! Supervises one PHP-FPM pool per PHP version. Pools start on the first
//! request that needs them and stop again after being idle for a while.

use std::collections::HashMap;
use std::path::PathBuf;
use std::process::Stdio;
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail};
use tokio::process::{Child, Command};
use tokio::sync::Mutex;

use crate::paths::paths;
use crate::php;

struct Pool {
    child: Child,
    started: Instant,
    last_used: Instant,
}

#[derive(Debug, serde::Serialize)]
pub struct PoolStatus {
    pub version: String,
    pub pid: Option<u32>,
    pub uptime_secs: u64,
    pub idle_secs: u64,
}

#[derive(Default)]
pub struct FpmManager {
    pools: Mutex<HashMap<String, Pool>>,
}

impl FpmManager {
    /// Socket of a running pool for `version`, starting it if needed.
    pub async fn socket_for(&self, version: &str) -> Result<PathBuf> {
        let mut pools = self.pools.lock().await;
        if let Some(pool) = pools.get_mut(version) {
            if pool.child.try_wait()?.is_none() {
                pool.last_used = Instant::now();
                return Ok(paths().fpm_socket(version));
            }
            tracing::warn!("php-fpm {version} exited; restarting");
            pools.remove(version);
        }
        let pool = spawn(version).await?;
        pools.insert(version.to_string(), pool);
        Ok(paths().fpm_socket(version))
    }

    /// Forget a pool whose socket stopped accepting connections.
    pub async fn mark_broken(&self, version: &str) {
        if let Some(pool) = self.pools.lock().await.remove(version) {
            stop_pool(version, pool).await;
        }
    }

    pub async fn stop(&self, version: Option<&str>) -> Vec<String> {
        let mut pools = self.pools.lock().await;
        let versions: Vec<String> = match version {
            Some(v) => pools.keys().filter(|k| *k == v).cloned().collect(),
            None => pools.keys().cloned().collect(),
        };
        for v in &versions {
            if let Some(pool) = pools.remove(v) {
                stop_pool(v, pool).await;
            }
        }
        versions
    }

    pub async fn reap_idle(&self, idle: Duration) {
        let mut pools = self.pools.lock().await;
        let idle_versions: Vec<String> = pools
            .iter()
            .filter(|(_, p)| p.last_used.elapsed() >= idle)
            .map(|(v, _)| v.clone())
            .collect();
        for v in idle_versions {
            if let Some(pool) = pools.remove(&v) {
                tracing::info!("stopping idle php-fpm {v}");
                stop_pool(&v, pool).await;
            }
        }
    }

    pub async fn status(&self) -> Vec<PoolStatus> {
        let pools = self.pools.lock().await;
        let mut out: Vec<PoolStatus> = pools
            .iter()
            .map(|(v, p)| PoolStatus {
                version: v.clone(),
                pid: p.child.id(),
                uptime_secs: p.started.elapsed().as_secs(),
                idle_secs: p.last_used.elapsed().as_secs(),
            })
            .collect();
        out.sort_by(|a, b| a.version.cmp(&b.version));
        out
    }
}

fn pool_config(version: &str) -> String {
    let p = paths();
    format!(
        "; Generated by Bird on every start; edit {ini} for PHP settings.\n\
         [global]\n\
         pid = {pid}\n\
         error_log = {log}\n\
         daemonize = no\n\
         \n\
         [bird]\n\
         listen = {sock}\n\
         listen.mode = 0600\n\
         pm = dynamic\n\
         pm.max_children = 10\n\
         pm.start_servers = 2\n\
         pm.min_spare_servers = 1\n\
         pm.max_spare_servers = 3\n\
         catch_workers_output = yes\n\
         decorate_workers_output = no\n\
         clear_env = no\n",
        ini = p.php_ini(version).display(),
        pid = p.fpm_pid(version).display(),
        log = p.fpm_log(version).display(),
        sock = p.fpm_socket(version).display(),
    )
}

/// Kills an FPM master left behind by a previous daemon (e.g. after a crash).
fn kill_stale(version: &str) {
    let pid_file = paths().fpm_pid(version);
    let Some(pid) = std::fs::read_to_string(&pid_file)
        .ok()
        .and_then(|s| s.trim().parse::<i32>().ok())
    else {
        return;
    };
    // Only kill it if it is still a php-fpm we started.
    let is_ours = std::process::Command::new("ps")
        .args(["-o", "command=", "-p", &pid.to_string()])
        .output()
        .map(|o| {
            String::from_utf8_lossy(&o.stdout)
                .contains(&paths().fpm_config(version).display().to_string())
        })
        .unwrap_or(false);
    if is_ours {
        tracing::info!("stopping stale php-fpm {version} (pid {pid})");
        unsafe { libc::kill(pid, libc::SIGTERM) };
        std::thread::sleep(Duration::from_millis(300));
    }
    let _ = std::fs::remove_file(pid_file);
}

async fn spawn(version: &str) -> Result<Pool> {
    if !php::is_installed(version) {
        bail!("PHP {version} is not installed. Run: bird php:install {version}");
    }
    let p = paths();
    std::fs::create_dir_all(p.run())?;
    std::fs::create_dir_all(p.log())?;
    std::fs::create_dir_all(p.php_conf_d(version))?;
    std::fs::write(p.fpm_config(version), pool_config(version))?;
    kill_stale(version);
    let socket = p.fpm_socket(version);
    let _ = std::fs::remove_file(&socket);

    let log = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(p.fpm_log(version))?;
    tracing::info!("starting php-fpm {version}");
    let mut child = Command::new(p.fpm_binary(version))
        .arg("--nodaemonize")
        .arg("--fpm-config")
        .arg(p.fpm_config(version))
        .arg("-c")
        .arg(p.php_ini(version))
        .env("PHP_INI_SCAN_DIR", p.php_conf_d(version))
        .stdin(Stdio::null())
        .stdout(log.try_clone()?)
        .stderr(log)
        .kill_on_drop(true)
        .spawn()
        .with_context(|| format!("could not start php-fpm {version}"))?;

    let deadline = Instant::now() + Duration::from_secs(10);
    loop {
        if tokio::net::UnixStream::connect(&socket).await.is_ok() {
            let now = Instant::now();
            return Ok(Pool {
                child,
                started: now,
                last_used: now,
            });
        }
        if let Some(status) = child.try_wait()? {
            bail!(
                "php-fpm {version} exited with {status} during startup:\n{}",
                tail(&p.fpm_log(version), 10)
            );
        }
        if Instant::now() > deadline {
            let _ = child.kill().await;
            bail!(
                "php-fpm {version} did not start within 10s:\n{}",
                tail(&p.fpm_log(version), 10)
            );
        }
        tokio::time::sleep(Duration::from_millis(20)).await;
    }
}

async fn stop_pool(version: &str, mut pool: Pool) {
    if let Some(pid) = pool.child.id() {
        // SIGQUIT = graceful: workers finish their current request.
        unsafe { libc::kill(pid as i32, libc::SIGQUIT) };
        if tokio::time::timeout(Duration::from_secs(5), pool.child.wait())
            .await
            .is_err()
        {
            tracing::warn!("php-fpm {version} did not stop in time; killing");
            let _ = pool.child.kill().await;
        }
    }
    let _ = std::fs::remove_file(paths().fpm_socket(version));
}

fn tail(path: &std::path::Path, lines: usize) -> String {
    let text = std::fs::read_to_string(path).unwrap_or_default();
    let all: Vec<&str> = text.lines().collect();
    all[all.len().saturating_sub(lines)..].join("\n")
}
