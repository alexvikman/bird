//! Supervises PHP-FPM pools: one per PHP version, plus an Xdebug pool per
//! version for requests that ask for a debug session. Pools start on the
//! first request that needs them and stop again after being idle a while.

use std::collections::HashMap;
use std::path::PathBuf;
use std::process::Stdio;
use std::time::{Duration, Instant};

use anyhow::{Context, Result, bail};
use tokio::process::{Child, Command};
use tokio::sync::Mutex;

use crate::paths::paths;
use crate::php;

struct Pool {
    child: Child,
    started: Instant,
    last_used: Instant,
}

/// Pool name: `8.4`, or `8.4-xdebug` for the Xdebug pool. Socket, config,
/// pid and log files are named after it.
pub fn pool_name(version: &str, xdebug: bool) -> String {
    if xdebug {
        format!("{version}-xdebug")
    } else {
        version.to_string()
    }
}

#[derive(Debug, serde::Serialize)]
pub struct PoolStatus {
    /// Pool name, e.g. `8.4` or `8.4-xdebug`.
    pub version: String,
    pub pid: Option<u32>,
    pub uptime_secs: u64,
    pub idle_secs: u64,
}

#[derive(Default)]
pub struct FpmManager {
    pools: Mutex<HashMap<String, Pool>>,
}

impl FpmManager {
    /// Socket of a running pool for `version` (its Xdebug pool when `xdebug`),
    /// starting it if needed.
    pub async fn socket_for(&self, version: &str, xdebug: bool) -> Result<PathBuf> {
        let name = pool_name(version, xdebug);
        let mut pools = self.pools.lock().await;
        if let Some(pool) = pools.get_mut(&name) {
            if pool.child.try_wait()?.is_none() {
                pool.last_used = Instant::now();
                return Ok(paths().fpm_socket(&name));
            }
            tracing::warn!("php-fpm {name} exited; restarting");
            pools.remove(&name);
        }
        let pool = spawn(version, xdebug).await?;
        pools.insert(name.clone(), pool);
        Ok(paths().fpm_socket(&name))
    }

    /// Forget a pool whose socket stopped accepting connections.
    pub async fn mark_broken(&self, version: &str, xdebug: bool) {
        let name = pool_name(version, xdebug);
        if let Some(pool) = self.pools.lock().await.remove(&name) {
            stop_pool(&name, pool).await;
        }
    }

    /// Stops all pools, or both pools of one PHP version.
    pub async fn stop(&self, version: Option<&str>) -> Vec<String> {
        let mut pools = self.pools.lock().await;
        let versions: Vec<String> = match version {
            Some(v) => pools
                .keys()
                .filter(|k| *k == v || **k == pool_name(v, true))
                .cloned()
                .collect(),
            None => pools.keys().cloned().collect(),
        };
        for v in &versions {
            if let Some(pool) = pools.remove(v) {
                stop_pool(v, pool).await;
            }
        }
        versions
    }

    pub async fn reap_idle(&self, idle: Duration) {
        let mut pools = self.pools.lock().await;
        let idle_versions: Vec<String> = pools
            .iter()
            .filter(|(_, p)| p.last_used.elapsed() >= idle)
            .map(|(v, _)| v.clone())
            .collect();
        for v in idle_versions {
            if let Some(pool) = pools.remove(&v) {
                tracing::info!("stopping idle php-fpm {v}");
                stop_pool(&v, pool).await;
            }
        }
    }

    pub async fn status(&self) -> Vec<PoolStatus> {
        let pools = self.pools.lock().await;
        let mut out: Vec<PoolStatus> = pools
            .iter()
            .map(|(v, p)| PoolStatus {
                version: v.clone(),
                pid: p.child.id(),
                uptime_secs: p.started.elapsed().as_secs(),
                idle_secs: p.last_used.elapsed().as_secs(),
            })
            .collect();
        out.sort_by(|a, b| a.version.cmp(&b.version));
        out
    }
}

fn pool_config(version: &str, name: &str) -> String {
    let p = paths();
    format!(
        "; Generated by Bird on every start; edit {ini} for PHP settings.\n\
         [global]\n\
         pid = {pid}\n\
         error_log = {log}\n\
         daemonize = no\n\
         \n\
         [bird]\n\
         listen = {sock}\n\
         listen.mode = 0600\n\
         pm = dynamic\n\
         pm.max_children = 10\n\
         pm.start_servers = 2\n\
         pm.min_spare_servers = 1\n\
         pm.max_spare_servers = 3\n\
         catch_workers_output = yes\n\
         decorate_workers_output = no\n\
         clear_env = no\n",
        ini = p.php_ini(version).display(),
        pid = p.fpm_pid(name).display(),
        log = p.fpm_log(name).display(),
        sock = p.fpm_socket(name).display(),
    )
}

/// Kills an FPM master left behind by a previous daemon (e.g. after a crash).
fn kill_stale(name: &str) {
    let pid_file = paths().fpm_pid(name);
    let Some(pid) = std::fs::read_to_string(&pid_file)
        .ok()
        .and_then(|s| s.trim().parse::<u32>().ok())
    else {
        return;
    };
    // Only kill it if it is still a php-fpm we started.
    let is_ours = std::process::Command::new("ps")
        .args(["-o", "command=", "-p", &pid.to_string()])
        .output()
        .map(|o| {
            String::from_utf8_lossy(&o.stdout)
                .contains(&paths().fpm_config(name).display().to_string())
        })
        .unwrap_or(false);
    if is_ours {
        tracing::info!("stopping stale php-fpm {name} (pid {pid})");
        let _ = crate::sys::signal(pid, libc::SIGTERM);
        std::thread::sleep(Duration::from_millis(300));
    }
    let _ = std::fs::remove_file(pid_file);
}

async fn spawn(version: &str, xdebug: bool) -> Result<Pool> {
    if !php::is_installed(version) {
        bail!("PHP {version} is not installed. Run: bird php:install {version}");
    }
    let name = pool_name(version, xdebug);
    let p = paths();
    std::fs::create_dir_all(p.run())?;
    std::fs::create_dir_all(p.log())?;
    std::fs::create_dir_all(p.php_conf_d(version))?;
    let scan_dirs = if xdebug {
        php::xdebug_scan_dirs(version)?
    } else {
        p.php_conf_d(version).into_os_string()
    };
    std::fs::write(p.fpm_config(&name), pool_config(version, &name))?;
    kill_stale(&name);
    let socket = p.fpm_socket(&name);
    let _ = std::fs::remove_file(&socket);

    let log = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(p.fpm_log(&name))?;
    tracing::info!("starting php-fpm {name}");
    let mut command = Command::new(p.fpm_binary(version));
    // Started from a tokio worker thread, which still holds the capability the
    // systemd unit grants for binding ports 80/443: PHP must not get it.
    #[cfg(target_os = "linux")]
    // SAFETY: the closure only makes system calls (no allocation, no locks),
    // so it is safe between fork and exec.
    unsafe {
        command.pre_exec(crate::sys::drop_capabilities);
    }
    let mut child = command
        .arg("--nodaemonize")
        .arg("--fpm-config")
        .arg(p.fpm_config(&name))
        .arg("-c")
        .arg(p.php_ini(version))
        .env("PHP_INI_SCAN_DIR", scan_dirs)
        .stdin(Stdio::null())
        .stdout(log.try_clone()?)
        .stderr(log)
        .kill_on_drop(true)
        .spawn()
        .with_context(|| format!("could not start php-fpm {name}"))?;

    let deadline = Instant::now() + Duration::from_secs(10);
    loop {
        if tokio::net::UnixStream::connect(&socket).await.is_ok() {
            let now = Instant::now();
            return Ok(Pool {
                child,
                started: now,
                last_used: now,
            });
        }
        if let Some(status) = child.try_wait()? {
            bail!(
                "php-fpm {name} exited with {status} during startup:\n{}",
                tail(&p.fpm_log(&name), 10)
            );
        }
        if Instant::now() > deadline {
            let _ = child.kill().await;
            bail!(
                "php-fpm {name} did not start within 10s:\n{}",
                tail(&p.fpm_log(&name), 10)
            );
        }
        tokio::time::sleep(Duration::from_millis(20)).await;
    }
}

async fn stop_pool(name: &str, mut pool: Pool) {
    if let Some(pid) = pool.child.id() {
        // SIGQUIT = graceful: workers finish their current request.
        let _ = crate::sys::signal(pid, libc::SIGQUIT);
        if tokio::time::timeout(Duration::from_secs(5), pool.child.wait())
            .await
            .is_err()
        {
            tracing::warn!("php-fpm {name} did not stop in time; killing");
            let _ = pool.child.kill().await;
        }
    }
    let _ = std::fs::remove_file(paths().fpm_socket(name));
}

fn tail(path: &std::path::Path, lines: usize) -> String {
    let text = std::fs::read_to_string(path).unwrap_or_default();
    let all: Vec<&str> = text.lines().collect();
    all[all.len().saturating_sub(lines)..].join("\n")
}
